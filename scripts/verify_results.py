"""Validate generated function-call results against the function schema.

Usage:
    python scripts/verify_results.py [results.json]

Every generated call must be a JSON object with ``prompt``, ``name`` and
``parameters`` keys, must reference a declared function, and must provide
exactly that function's parameters with the declared JSON types.

Exit status is 0 when the file is valid, 1 otherwise.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

TYPE_CHECKS: dict[str, tuple[type, ...]] = {
    "number": (int, float),
    "string": (str,),
    "boolean": (bool,),
}

DEFAULT_FUNCTIONS_PATH = Path("data/input/functions_definition.json")


def load_json(path: Path) -> Any:
    """Load and return the JSON document stored at *path*."""
    with path.open("r", encoding="utf-8") as file:
        return json.load(file)


def validate_results(results: Any, functions: Any) -> list[str]:
    """Return a list of human-readable problems found in *results*."""
    errors: list[str] = []

    if not isinstance(results, list):
        return ["results must be a JSON array"]
    if not isinstance(functions, list):
        return ["function definitions must be a JSON array"]

    definitions = {
        definition["name"]: definition
        for definition in functions
        if isinstance(definition, dict) and "name" in definition
    }

    for index, result in enumerate(results):
        prefix = f"result[{index}]"
        if not isinstance(result, dict):
            errors.append(f"{prefix}: not a JSON object")
            continue
        if set(result) != {"prompt", "name", "parameters"}:
            errors.append(f"{prefix}: expected keys prompt, name, parameters")
            continue

        name = result["name"]
        definition = definitions.get(name) if isinstance(name, str) else None
        if definition is None:
            errors.append(f"{prefix}: unknown function {name!r}")
            continue

        parameters = result["parameters"]
        if not isinstance(parameters, dict):
            errors.append(f"{prefix}: parameters is not a JSON object")
            continue

        expected_parameters = definition.get("parameters", {})
        if set(parameters) != set(expected_parameters):
            errors.append(
                f"{prefix}: parameters {sorted(parameters)} do not match "
                f"{sorted(expected_parameters)}"
            )
            continue

        for parameter_name, value in parameters.items():
            declared = expected_parameters[parameter_name]
            expected_type = (
                declared.get("type") if isinstance(declared, dict) else None
            )
            checks = TYPE_CHECKS.get(expected_type or "", ())
            if not checks:
                errors.append(
                    f"{prefix}.{parameter_name}: "
                    f"unsupported type {expected_type!r}"
                )
                continue
            is_valid = isinstance(value, checks)
            if expected_type == "number":
                is_valid = is_valid and not isinstance(value, bool)
            if not is_valid:
                errors.append(
                    f"{prefix}.{parameter_name}: expected {expected_type}, "
                    f"got {type(value).__name__}"
                )

    return errors


def main() -> int:
    """Run the validation and report the outcome."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "results",
        type=Path,
        nargs="?",
        default=Path("data/output/function_calling_results.json"),
        help="results file generated by `python -m src`",
    )
    parser.add_argument(
        "--functions",
        type=Path,
        default=DEFAULT_FUNCTIONS_PATH,
        help="function definitions used for the run",
    )
    args = parser.parse_args()

    try:
        results = load_json(args.results)
        functions = load_json(args.functions)
    except (OSError, json.JSONDecodeError) as error:
        print(f"✗ could not read input: {error}", file=sys.stderr)
        return 1

    errors = validate_results(results, functions)
    if errors:
        print(
            f"✗ {len(errors)} problem(s) found in {args.results}:",
            file=sys.stderr,
        )
        for problem in errors:
            print(f"  - {problem}", file=sys.stderr)
        return 1

    count = len(results) if isinstance(results, list) else 0
    print(f"✓ {count} call(s) valid and schema-compliant in {args.results}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
